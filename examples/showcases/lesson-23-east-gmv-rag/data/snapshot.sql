BEGIN;
CREATE TABLE cell_dim (
  cell TEXT PRIMARY KEY, channel TEXT NOT NULL, entry TEXT NOT NULL,
  family TEXT NOT NULL, site TEXT NOT NULL
);
CREATE TABLE sales_day (
  day DATE NOT NULL, region TEXT NOT NULL, cell TEXT NOT NULL REFERENCES cell_dim(cell),
  visits INTEGER NOT NULL, paid_orders INTEGER NOT NULL, paid_fen INTEGER NOT NULL, units INTEGER NOT NULL,
  PRIMARY KEY (day, region, cell)
);
CREATE TABLE ad_slot (
  day DATE NOT NULL, region TEXT NOT NULL, plan TEXT NOT NULL, slot TEXT NOT NULL,
  spend_fen INTEGER NOT NULL, impressions INTEGER NOT NULL, clicks INTEGER NOT NULL, landings INTEGER NOT NULL,
  PRIMARY KEY (day, region, plan, slot)
);
CREATE TABLE entry_audit (
  day DATE NOT NULL, region TEXT NOT NULL, cell TEXT NOT NULL REFERENCES cell_dim(cell),
  raw_open_events INTEGER NOT NULL, retry_events INTEGER NOT NULL, unlinked_opens INTEGER NOT NULL, visits INTEGER NOT NULL,
  PRIMARY KEY (day, region, cell)
);
CREATE TABLE stock_day (
  day DATE NOT NULL, region TEXT NOT NULL, pool TEXT NOT NULL, sku_size INTEGER NOT NULL,
  attempts INTEGER NOT NULL, short_rejects INTEGER NOT NULL, other_rejects INTEGER NOT NULL, sellable_close INTEGER NOT NULL,
  PRIMARY KEY (day, region, pool, sku_size)
);
CREATE TABLE stock_event (
  ts TIMESTAMP NOT NULL, region TEXT NOT NULL, pool TEXT NOT NULL, sku_size INTEGER NOT NULL,
  doc_no TEXT NOT NULL, event TEXT NOT NULL, qty INTEGER NOT NULL,
  PRIMARY KEY (region, pool, doc_no, sku_size, event)
);
CREATE TABLE coupon_day (
  day DATE NOT NULL, region TEXT NOT NULL, site TEXT NOT NULL, offer TEXT NOT NULL,
  checks INTEGER NOT NULL, eligible INTEGER NOT NULL, issued INTEGER NOT NULL, redeemed INTEGER NOT NULL, discount_fen INTEGER NOT NULL,
  PRIMARY KEY (day, region, site, offer)
);
CREATE TABLE refund_day (
  day DATE NOT NULL, region TEXT NOT NULL, cash_refund_fen INTEGER NOT NULL, cohort_d7_fen INTEGER NOT NULL,
  PRIMARY KEY (day, region)
);
CREATE TABLE source_day (
  day DATE NOT NULL, region TEXT NOT NULL, asset TEXT NOT NULL, expected_parts INTEGER NOT NULL,
  first_parts INTEGER NOT NULL, final_parts INTEGER NOT NULL, state TEXT NOT NULL, final_at TIMESTAMP NOT NULL,
  PRIMARY KEY (day, region, asset)
);

